function fcn_write_macros(macros, filename, header)
% FCN_WRITE_MACROS  Write numbers as LaTeX macros so text, tables and figures share one source.
%
%   fcn_write_macros(macros, 'CICADAS_II_Paper_Draft/results_macros.tex')
%
% macros: N x 2 or N x 3 cell array {name, value, fmt}
%   name  - macro name WITHOUT backslash, letters only (LaTeX rule), e.g. 'QuadHSLDAdaptSurv'
%   value - number or char
%   fmt   - sprintf format for numbers (default '%.1f')
%
% In main.tex:  \input{results_macros}   then write e.g.  survival was \QuadHSLDAdaptSurv\%.
% Re-running an experiment and this writer updates every number in the paper
% at once, which removes the figure/table/text mismatches (G1-G4, R1 Major 7c).
% Macros are written with \providecommand + \renewcommand so the file can be
% \input more than once without errors.

if nargin < 3, header = ''; end
fid = fopen(filename, 'w');
if fid < 0, error('Cannot open %s for writing', filename); end
fprintf(fid, '%% AUTO-GENERATED by fcn_write_macros on %s. Do not edit by hand.\n', datestr(now, 'yyyy-mm-dd HH:MM'));
if ~isempty(header), fprintf(fid, '%% %s\n', header); end

seen = {};
for i = 1:size(macros, 1)
    name = macros{i, 1};
    if isempty(regexp(name, '^[A-Za-z]+$', 'once'))
        fclose(fid);
        error('Macro name "%s" must contain letters only (LaTeX rule). Spell digits out, e.g. OmegaTwo.', name);
    end
    if any(strcmp(seen, name))
        fclose(fid);
        error('Duplicate macro name "%s".', name);
    end
    seen{end+1} = name; %#ok<AGROW>
    val = macros{i, 2};
    if size(macros, 2) >= 3 && ~isempty(macros{i, 3}), fmt = macros{i, 3}; else, fmt = '%.1f'; end
    if isnumeric(val) || islogical(val)
        s = sprintf(fmt, val);
        s = strrep(s, '-', '\ensuremath{-}');   % proper minus sign in text mode
    else
        s = val;
    end
    fprintf(fid, '\\providecommand{\\%s}{}\\renewcommand{\\%s}{%s}\n', name, name, s);
end
fclose(fid);
fprintf('Wrote %d macros to %s\n', size(macros, 1), filename);

end
